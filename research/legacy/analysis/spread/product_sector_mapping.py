# 辅助函数：根据文件名提取代码并查找板块
def get_sector_from_filename(filename):
    """
    从 '白砂糖_SR_factors_with_ohlc.csv' 这样的文件名中
    提取产品代码 'sr' 并返回对应的板块名称。
    """
    try:
        # 假设文件名格式为 '中文名_代码_...'
        product_code = filename.split('_')[1].lower()
        return SECTOR_MAP.get(product_code, '未分类') # 如果找不到，则归为'未分类'
    except:
        return None # 无法解析的文件名